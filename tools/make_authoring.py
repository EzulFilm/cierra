"""Write docs/ops_manifest.json and docs/authoring.md (the LLM / author-facing profile) from the op table and
cierra/examples.py. tests/test_authoring.py fails when they are stale.

    python tools/make_authoring.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from cierra.manifest import manifest  # noqa: E402


def manifest_text():
    return json.dumps(manifest(), indent=1, sort_keys=True) + "\n"


def authoring_text():
    from cierra.checker import check
    from cierra.errors import CierraError
    from cierra.examples import GUIDANCE, INVALID, VALID
    from cierra.llm import op_table
    from cierra.parser import parse
    out = ["# Cierra 0.1 authoring profile",
           "",
           "For people and LLMs writing programs. Generated by tools/make_authoring.py from the op table and",
           "cierra/examples.py; the full maths is in [spec.md](spec.md), the machine-readable table in",
           "[ops_manifest.json](ops_manifest.json).",
           "",
           "## Rules of thumb", ""]
    out += [f"- {g}" for g in GUIDANCE]
    out += ["", "## Loop", "",
            "generate → parse / check → canonicalise → lint (with the host's context: clip length, planes, segment "
            "ids, targets) → render a preview → measure → revise with the diagnostics and numbers; at most N rounds; "
            "every accepted version committed with its diff.", "",
            "## Examples (each passes the checker with no warnings)", ""]
    for title, src in VALID:
        check(parse(src))
        out += [f"### {title}", "", "```", src.rstrip(), "```", ""]
    out += ["## Mistakes and the checker's answer", ""]
    for title, src, _ in INVALID:
        try:
            check(parse(src))
            msg = "(accepted?)"
        except CierraError as e:
            msg = str(e)
        out += [f"### {title}", "", "```", src.rstrip(), "```", "", "```", msg, "```", ""]
    out += ["## Operations", "", "```", op_table(), "```", ""]
    return "\n".join(out)


def main():
    (ROOT / "docs" / "ops_manifest.json").write_text(manifest_text(), encoding="utf-8")
    (ROOT / "docs" / "authoring.md").write_text(authoring_text(), encoding="utf-8")
    print("wrote docs/ops_manifest.json, docs/authoring.md")


if __name__ == "__main__":
    main()
