def test_acescct_reference_values():
    # S-2016-001: the linear segment meets the log segment at 0.0078125 -> 0.155251141552511; 18 % grey -> 0.4135884
    assert math.isclose(float(C.acescct_encode(np.array(0.18))), (math.log2(0.18) + 9.72) / 17.52, rel_tol=1e-15)
    assert abs(float(C.acescct_encode(np.array(0.18))) - 0.4135884) < 1e-7
    assert abs(float(C.acescct_encode(np.array(0.0078125))) - 0.155251141552511) < 1e-12
    x = np.array([0.0, 0.001, 0.0078125, 0.01, 0.18, 1.0, 100.0])
    assert np.allclose(C.acescct_decode(C.acescct_encode(x)), x, rtol=1e-12, atol=1e-15)


