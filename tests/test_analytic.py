def test_curve_extrapolation_is_the_spec_formula():
    # points (0,0) (0.5,1) (1,1): secants 2, 0; m0 = 2, m1 = 1, m2 = 0; Fritsch-Carlson leaves them (a^2+b^2 < 9)
    x = np.array([-0.1, 0.0, 0.5, 1.0, 1.2])
    assert np.allclose(monotone_curve(x, [(0, 0), (0.5, 1), (1, 1)]), [-0.2, 0.0, 1.0, 1.0, 1.0])
    # close points at the minimum spacing: exact secant (no clamp)
    y = monotone_curve(np.array([-1.0]), [(0, 0), (1e-4, 1), (1, 1)])
    assert math.isclose(y[0], -1e4, rel_tol=1e-9)


