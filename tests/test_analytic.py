def test_blend_modes_analytically():
    def run(mode, b_stops, t_stops, opacity=1.0):
        prog = load(f"cierra 0.1\noutput acescct()\nnode b = exposure(stops: {b_stops})\n"
                    f"node t = exposure(stops: {t_stops})\ngraph layer(b, t, mode: {mode}, opacity: {opacity})\n")
        return float(grade_working(np.full((3, 1, 1), float(C.acescct_encode(np.array(0.18)))), prog)[0, 0, 0])
    lin = lambda v: float(C.acescct_decode(np.array(v)))  # noqa: E731
    assert math.isclose(lin(run("add", 0, 0)), 0.36, rel_tol=1e-12)
    assert math.isclose(lin(run("multiply", 0, 1)), 0.18 * 0.36 / 0.18, rel_tol=1e-12)
    assert math.isclose(lin(run("lighten", 0, 1)), 0.36, rel_tol=1e-12)
    assert math.isclose(lin(run("darken", 0, 1)), 0.18, rel_tol=1e-12)
    g = float(C.acescct_encode(np.array(0.18)))
    assert math.isclose(run("normal", 0, 1, 0.25), g + 0.25 / 17.52, rel_tol=1e-12)
    assert math.isclose(lin(run("subtract", 1, 0)), 0.18, rel_tol=1e-12)
    assert math.isclose(lin(run("difference", 0, 1)), 0.18, rel_tol=1e-12)
    t = g + 1 / 17.52
    assert math.isclose(run("screen", 0, 1), 1 - (1 - g) * (1 - t), rel_tol=1e-12)
    assert math.isclose(run("overlay", 0, 1), 2 * g * t, rel_tol=1e-12)  # grey code value is below 0.5


def test_masks_analytically():
    from cierra.engine import make_ctx, mask_value
    code = np.full((3, 1, 3), 0.0)
    code[:, 0, 0], code[:, 0, 1], code[:, 0, 2] = 0.2, 0.5, 0.8  # greys: luma = value
    prog = load("cierra 0.1\nnode a = exposure(stops: 1)\n  mask luma(range: 0.3..0.6, soft: 0)\ngraph a\n")
    assert mask_value(code, prog.nodes["a"].mask, make_ctx(prog, 3)).tolist() == [[0.0, 1.0, 0.0]]
    win = load("cierra 0.1\nnode a = exposure(stops: 1)\n  mask window(centre: [0.5, 0], radius: [0.2, 0.2], "
               "soft: 0.1)\ngraph a\n")
    assert mask_value(code, win.nodes["a"].mask, make_ctx(win, 3)).tolist() == [[0.0, 1.0, 0.0]]
    hue = load("cierra 0.1\nnode a = exposure(stops: 1)\n  mask qualifier(hue: 100..140, soft: 0)\ngraph a\n")
    red = np.array([0.6, 0.4, 0.4]).reshape(3, 1, 1)  # Cb < 0, Cr > 0: hue ~ 123
    blue = np.array([0.4, 0.4, 0.6]).reshape(3, 1, 1)
    grey = np.full((3, 1, 1), 0.4)
    vals = [float(mask_value(c, hue.nodes["a"].mask, make_ctx(hue, 1))[0, 0]) for c in (red, blue, grey)]
    assert vals == [1.0, 0.0, 0.0]


