def test_key_poly_matches_key_value():
    import random
    from cierra.engine import key_poly
    rng = random.Random(7)
    for _ in range(300):
        frames = sorted(rng.sample(range(0, 40), rng.randint(1, 5)))
        k = A.Keys(rng.choice(["step", "linear", "smooth"]), tuple((f, rng.uniform(1, 10)) for f in frames))
        bounds = [0] + frames + [45]
        for a, b in zip(bounds, bounds[1:]):
            if b <= a:
                continue
            p = key_poly(k, a, b)
            for f in range(a, b):
                assert abs(p(f) - key_value(k, f)) < 1e-9, (k, a, b, f)


def test_knee_check_equals_brute_force():
    """The checker's verdict equals a scan of every integer frame, on 600 random animated pairs."""
    import random
    rng = random.Random(20261027)

    def keys_text(lo, hi):
        if rng.random() < 0.25:
            return f"{rng.uniform(lo, hi):.3f}", None
        frames = sorted(rng.sample(range(0, 30), rng.randint(1, 4)))
        vals = [round(rng.uniform(lo, hi), 3) for _ in frames]
        interp = rng.choice(["step", "linear", "smooth"])
        return (f"keys({interp}, " + ", ".join(f"{f}: {v}" for f, v in zip(frames, vals)) + ")",
                A.Keys(interp, tuple(zip(frames, vals))))

    accepted = rejected = 0
    for _ in range(600):
        (kt, kk), (mt, mk) = keys_text(1, 10), keys_text(1.5, 12)
        kv = (lambda f: key_value(kk, f)) if kk else (lambda f, c=float(kt): c)
        mv = (lambda f: key_value(mk, f)) if mk else (lambda f, c=float(mt): c)
        truth = all(kv(f) < mv(f) for f in range(0, 31))
        try:
            load(_knee_src(kt, mt))
            ok = True
        except CierraError as e:
            assert "max_stops" in str(e), str(e)
            ok = False
        assert ok == truth, (kt, mt)
        accepted += ok
        rejected += not ok
    assert accepted > 50 and rejected > 50  # both outcomes are exercised


