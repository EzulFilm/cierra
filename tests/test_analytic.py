    answers = [f"```cierra\n{KEYED_BLUR}```\nmessage: keyed blur",
               "```cierra\ncierra 0.1\nnode s = photo_to_scene(knee_stops: keys(linear, 0: 4, 10: 7), "
               "max_stops: 6)\nphoto_graph s\n```\nmessage: bad knee"]
