def test_aces2_output_has_no_black_holes():
    """OCIO 2.6's default CPU optimisation mapped rare bright values to exact black (found by a live
    grading-app test: two spark pixels). colour.aces2_display repairs them; a dense scan around the value finds none."""
    x = np.array([1.02502234, 0.90455188, 0.68137096])
    rng = np.random.default_rng(0)
    pts = (x[:, None] + rng.uniform(-0.01, 0.01, (3, 200000))).reshape(3, 1, -1)
    for display in ("srgb", "rec1886"):
        out = C.aces2_display(pts, display)
        assert (out.max(0) > 0.9).all(), int((out.max(0) <= 0.9).sum())


def test_aces2_patch_holds_over_the_whole_range():
    """The local patch for the OCIO 2.6 ACES 2.0 NaN (colour.aces2_display): over random ACEScct 0..1.4 no input
    brighter than luma 0.15 comes out black, for both displays (OCIO alone: 2 in 3 million, at luma >= 0.8); and the
    inverse transform gives finite values for every display value."""
    rng = np.random.default_rng(2)
    x = rng.uniform(0.0, 1.4, (3, 1, 1000000))
    lum = C.luma_cv(x)[0]
    for display in ("srgb", "rec1886"):
        out = C.aces2_display(x, display)[:, 0]
        assert not ((out <= 0).all(0) & (lum > 0.15)).any(), display
        # a bright saturated blue (luma 0.18): missed by the first patch, which gated on luma (independent review)
        blue = C.aces2_display(np.array([0.12630391, 0.10264291, 1.11055911]).reshape(3, 1, 1), display)
        assert blue.min() > 0.99, blue.ravel()
        inv = C.aces2_inverse(np.ascontiguousarray(rng.uniform(0, 1, (3, 1, 200000))), display)
        assert np.isfinite(inv).all(), display
